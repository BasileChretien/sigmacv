"""Write an approved information sheet (.docx) of study 2026-0310 as a TS module.

    python -X utf8 -I scripts/consent-sheet-from-docx.py <locale> <sheet.docx> "<document version>"

writes src/lib/research/consent/sheet.<locale>.ts. Needs python-docx. The
approved documents live in the maintainer's Ethics/ folder, which is not in
the repository; only the generated modules are.

The text is copied word for word. Only the presentation changes:
  - in the pandoc-made sheets (English, and the other languages an amendment
    will add), the headings are Word heading styles and the lists are written
    inline as " - " items, which become lists;
  - in the Japanese sheet (the committee's 別記様式第３号), the sections are
    "１．…" lines, "（１）…" and "○…" lines are sub-headings and "・" lines
    are list items;
  - the paper-only fields (date of explanation, signatures) and the form
    template's header are left out.
The script stops if a paragraph holds a line break or a tab, which a word for
word copy could not keep.
"""
import json
import re
import sys

import docx
from docx.text.paragraph import Paragraph

OUT = "src/lib/research/consent/sheet.{locale}.ts"

HEADER = """/**
 * GENERATED by scripts/consent-sheet-from-docx.py from the approved
 * information sheet ({version}). Never edit by hand: regenerate from an
 * approved document. The text is the document's, word for word.
 */
import type {{ InformationSheet }} from "./types";

export const {name}: InformationSheet = {body};
"""

PAPER_ONLY = ("Date of explanation (CE)", "説明日", "説明者署名")
JA_SECTION = re.compile(r"^[０-９0-9]{1,2}\s*[．.]")
JA_SUB = re.compile(r"^(（[０-９0-9]+）|○)")
# A line break or a tab character in a run (a page break, or a tab stop in the
# paragraph's properties, changes no text).
BREAK = re.compile(r"<w:br(?![^>]*w:type=\"page\")[^>]*>|<w:tab\s*/>")


def paragraphs(path):
    d = docx.Document(path)
    for child in d.element.body.iterchildren():
        tag = child.tag.split("}")[-1]
        if tag == "tbl":
            raise SystemExit("a table in the sheet: extend the script before generating")
        if tag != "p":
            continue
        p = Paragraph(child, d)
        text = p.text.strip()
        if not text or text.startswith(PAPER_ONLY):
            continue
        if BREAK.search(p._p.xml):
            raise SystemExit(f"a line break or tab inside: {text[:60]!r}")
        yield p.style.name, text


def styled_sheet(path):
    sheet = {"title": None, "preamble": [], "sections": []}
    for style, text in paragraphs(path):
        if style == "Heading 1":
            sheet["title"] = text
        elif style == "Heading 2":
            sheet["sections"].append({"heading": text, "blocks": []})
        elif not sheet["sections"]:
            sheet["preamble"].append(text)
        else:
            parts = text.split(" - ")
            blocks = sheet["sections"][-1]["blocks"]
            blocks.append({"kind": "p", "text": parts[0].strip()})
            if len(parts) > 1:
                blocks.append({"kind": "list", "items": [x.strip() for x in parts[1:]]})
    return sheet


def japanese_sheet(path):
    sheet = {"title": None, "preamble": [], "sections": []}
    for _, text in paragraphs(path):
        if sheet["title"] is None:
            sheet["title"] = text
        elif JA_SECTION.match(text):
            sheet["sections"].append({"heading": text, "blocks": []})
        elif not sheet["sections"]:
            sheet["preamble"].append(text)
        else:
            blocks = sheet["sections"][-1]["blocks"]
            if text.startswith("・"):
                if blocks and blocks[-1]["kind"] == "list":
                    blocks[-1]["items"].append(text[1:].strip())
                else:
                    blocks.append({"kind": "list", "items": [text[1:].strip()]})
            elif JA_SUB.match(text):
                blocks.append({"kind": "sub", "text": text})
            else:
                blocks.append({"kind": "p", "text": text})
    return sheet


def main(locale, path, version):
    sheet = japanese_sheet(path) if locale == "ja-JP" else styled_sheet(path)
    if not sheet["title"] or len(sheet["sections"]) != 19:
        raise SystemExit(f"expected a title and 19 sections, got {len(sheet['sections'])}")
    name = "SHEET_" + locale.replace("-", "_").upper()
    body = json.dumps(sheet, ensure_ascii=False, indent=2)
    out = OUT.format(locale=locale)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER.format(version=version, name=name, body=body))
    print(f"wrote {out}: {len(sheet['sections'])} sections; now run: npx prettier --write {out}")


if __name__ == "__main__":
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    main(*sys.argv[1:])
